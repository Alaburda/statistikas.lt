# Synthetic Lithuanian student questionnaire for the /analize survey demo.
#
# Writes:
#   src/data/apklausa.ts            – the demo dataset (TypeScript)
#   public/samples/apklausa.sav     – the same data as an SPSS file (downloadable sample)
#   src/data/fixtures/apklausa.sav  – identical copy used by the .sav import tests
#
# Run from _analize-src/:  Rscript scripts/make-survey-demo.R
# Fixed seed, so re-running produces byte-identical data.

suppressPackageStartupMessages({
  library(haven)
  library(jsonlite)
})

set.seed(20261017)
n <- 200

clamp <- function(x, lo, hi) pmin(pmax(x, lo), hi)
likert <- function(latent, loading, reverse = FALSE) {
  signal <- if (reverse) -loading * latent else loading * latent
  as.integer(clamp(round(3 + signal + rnorm(length(latent), 0, 0.75)), 1, 5))
}

lytis   <- sample(1:2, n, replace = TRUE, prob = c(0.38, 0.62))
amzius  <- as.integer(clamp(round(19 + rgamma(n, shape = 2, scale = 1.6)), 18, 35))
kursas  <- sample(1:4, n, replace = TRUE, prob = c(0.32, 0.27, 0.23, 0.18))
sritis  <- sample(1:4, n, replace = TRUE, prob = c(0.35, 0.15, 0.30, 0.20))
dirba   <- rbinom(n, 1, plogis(-1.2 + 0.45 * (kursas - 1)))

# Latent stress: higher for health sciences and for students who work.
stress  <- rnorm(n) + c(0, 0.15, 0.35, 0.6)[sritis] + 0.4 * dirba + 0.2 * (lytis == 2)
stress  <- as.numeric(scale(stress))
# Satisfaction is negatively related to stress.
satisf  <- as.numeric(scale(-0.45 * stress + rnorm(n, 0, 0.9) + c(0.2, 0, -0.1, 0.1)[sritis]))

S <- sapply(1:6, function(i) likert(stress, 0.95, reverse = i %in% c(3, 5)))
P <- sapply(1:8, function(i) likert(satisf, 0.9, reverse = i %in% c(2, 6)))
colnames(S) <- paste0("S", 1:6)
colnames(P) <- paste0("P", 1:8)

miegas  <- round(clamp(7.2 - 0.45 * stress + rnorm(n, 0, 0.8), 4, 10), 1)
vidurkis <- round(clamp(8 + 0.35 * satisf - 0.15 * stress + rnorm(n, 0, 0.8), 5, 10), 2)
# Pre/post wellbeing (0–100) around a 4-week mindfulness programme.
savijauta_pries <- round(clamp(58 - 6 * stress + rnorm(n, 0, 9), 10, 100))
savijauta_po    <- round(clamp(savijauta_pries + 4 + rnorm(n, 0, 7), 10, 100))

d <- data.frame(
  id = 1:n, lytis, amzius, kursas, sritis, dirba,
  S, P, miegas, vidurkis, savijauta_pries, savijauta_po
)

# Realistic item non-response: ~2 % missing on a few columns.
for (col in c("S4", "P5", "miegas", "vidurkis", "savijauta_po")) {
  d[[col]][sample(n, 4)] <- NA
}

# ---------- metadata ----------
item_text <- c(
  S1 = "Jaučiuosi pervargęs dėl studijų",
  S2 = "Man sunku atsipalaiduoti",
  S3 = "Lengvai susidoroju su studijų krūviu",
  S4 = "Nerimauju dėl atsiskaitymų",
  S5 = "Jaučiuosi ramus prieš egzaminus",
  S6 = "Dėl studijų prastai miegu",
  P1 = "Esu patenkintas pasirinkta programa",
  P2 = "Dažnai galvoju nutraukti studijas",
  P3 = "Dėstytojai yra kompetentingi",
  P4 = "Studijos atitinka mano lūkesčius",
  P5 = "Rekomenduočiau šią programą draugui",
  P6 = "Studijų turinys man neįdomus",
  P7 = "Gaunu pakankamai grįžtamojo ryšio",
  P8 = "Jaučiuosi universiteto bendruomenės dalimi"
)
likert_labels <- c(
  "1" = "Visiškai nesutinku", "2" = "Nesutinku", "3" = "Nei sutinku, nei nesutinku",
  "4" = "Sutinku", "5" = "Visiškai sutinku"
)

vars <- list(
  list(key = "id", label = "Respondento Nr.", type = "numeric"),
  list(key = "lytis", label = "Lytis", type = "categorical",
       valueLabels = list("1" = "Vyras", "2" = "Moteris")),
  list(key = "amzius", label = "Amžius", type = "numeric", unit = "m."),
  list(key = "kursas", label = "Kursas", type = "categorical",
       valueLabels = list("1" = "1 kursas", "2" = "2 kursas", "3" = "3 kursas", "4" = "4 kursas")),
  list(key = "sritis", label = "Studijų sritis", type = "categorical",
       valueLabels = list("1" = "Socialiniai mokslai", "2" = "Humanitariniai mokslai",
                          "3" = "Technologijos ir gamta", "4" = "Sveikatos mokslai")),
  list(key = "dirba", label = "Dirba studijuodamas", type = "categorical",
       valueLabels = list("0" = "Ne", "1" = "Taip"))
)
for (k in names(item_text)) {
  vars[[length(vars) + 1]] <- list(key = k, label = paste0(k, ". ", item_text[[k]]), type = "numeric")
}
vars <- c(vars, list(
  list(key = "miegas", label = "Miego trukmė", type = "numeric", unit = "val."),
  list(key = "vidurkis", label = "Studijų vidurkis", type = "numeric"),
  list(key = "savijauta_pries", label = "Savijauta prieš programą", type = "numeric"),
  list(key = "savijauta_po", label = "Savijauta po programos", type = "numeric")
))

# ---------- TypeScript ----------
row_json <- vapply(seq_len(n), function(i) {
  as.character(toJSON(as.list(d[i, ]), auto_unbox = TRUE, na = "null", digits = NA))
}, character(1))
ts <- c(
  "// Auto-generated by scripts/make-survey-demo.R – do not edit by hand.",
  "// Synthetic student questionnaire (n = 200): demographics, a 6-item stress scale",
  "// (S3, S5 reverse-keyed), an 8-item satisfaction scale (P2, P6 reverse-keyed),",
  "// and a pre/post wellbeing measure. Fixed seed; no real respondents.",
  "import type { Dataset } from \"../types\";",
  "",
  "const rows = [",
  paste0("  ", row_json, ","),
  "];",
  "",
  paste0("export const apklausa: Dataset = ", as.character(toJSON(list(
    name = "Studentų apklausa",
    description = paste(
      "Sintetiniai 200 studentų apklausos duomenys: demografija, streso (S1–S6) ir",
      "pasitenkinimo studijomis (P1–P8) skalės (1–5), savijauta prieš ir po programos."
    )
  ), auto_unbox = TRUE)) |> sub(pattern = "}$", replacement = ""),
  ",\"variables\": ", as.character(toJSON(vars, auto_unbox = TRUE, pretty = FALSE)),
  ", rows } as Dataset;")
)
writeLines(ts, "src/data/apklausa.ts", useBytes = TRUE)

# ---------- SPSS ----------
sav <- d
attr(sav$id, "label") <- "Respondento Nr."
sav$lytis  <- labelled(sav$lytis, c(Vyras = 1, Moteris = 2), label = "Lytis")
sav$amzius <- structure(sav$amzius, label = "Amžius")
sav$kursas <- labelled(sav$kursas, setNames(1:4, paste(1:4, "kursas")), label = "Kursas")
sav$sritis <- labelled(sav$sritis, c("Socialiniai mokslai" = 1, "Humanitariniai mokslai" = 2,
                                     "Technologijos ir gamta" = 3, "Sveikatos mokslai" = 4),
                       label = "Studijų sritis")
sav$dirba  <- labelled(sav$dirba, c(Ne = 0, Taip = 1), label = "Dirba studijuodamas")
for (k in names(item_text)) {
  sav[[k]] <- labelled(as.numeric(sav[[k]]),
                       setNames(as.numeric(names(likert_labels)), likert_labels),
                       label = paste0(k, ". ", item_text[[k]]))
}
attr(sav$miegas, "label") <- "Miego trukmė"
attr(sav$vidurkis, "label") <- "Studijų vidurkis"
attr(sav$savijauta_pries, "label") <- "Savijauta prieš programą"
attr(sav$savijauta_po, "label") <- "Savijauta po programos"

dir.create("public/samples", showWarnings = FALSE, recursive = TRUE)
dir.create("src/data/fixtures", showWarnings = FALSE, recursive = TRUE)
write_sav(sav, "public/samples/apklausa.sav")
write_sav(sav, "src/data/fixtures/apklausa.sav", compress = "byte")
# Uncompressed variant, plus a user-missing fixture (99 = "Neatsakė"), for the reader tests.
write_sav(sav, "src/data/fixtures/apklausa-uncompressed.sav", compress = "none")
um <- data.frame(
  q = labelled_spss(c(1, 2, 99, 3, NA), c("Neatsakė" = 99), na_values = 99, label = "Klausimas"),
  vardas = c("Ąžuolas", "Eglė", "Šarūnas", "Žydrūnė", "")
)
write_sav(um, "src/data/fixtures/user-missing.sav", compress = "none")

cat("Wrote", n, "rows.\n")
